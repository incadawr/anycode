/**
 * Compiled-in OFFICIAL plugin channel trust anchors (Taskana 4732 S1-B,
 * design §4): the ed25519 public keys the signed official plugin index is
 * verified against, the official index URL, and the extraction/network caps
 * the store and index client enforce.
 *
 * VALUE-ONLY module — importable by main, preload and renderer alike with
 * zero transitive deps, mirroring shared/skills-config.ts's contract. The
 * actual verification lives in main/plugins/index-client.ts (node:crypto).
 *
 * §9.14: until the owner generates production keys (owner ops, outside the
 * briefs), `OFFICIAL_PLUGIN_KEYS` holds ONLY a test key. A test key is
 * usable in non-packaged builds; a PACKAGED build whose key list carries
 * only test keys reports index status "not configured" (the official
 * channel is disabled, nothing auto-installs).
 */

/**
 * Marks a key as TEST-ONLY: generated by `scripts/plugins/keygen.mjs --test`
 * for local index authoring and CI. Never a production trust anchor — the
 * packaged-build gate below refuses a key list that holds only test keys.
 */
export const OFFICIAL_PLUGIN_TEST_KEY_ID_PREFIX = "test-";

export interface OfficialPluginKey {
  /** e.g. `ac-2026-1`; `test-*` ids are test keys (§9.14). */
  keyId: string;
  /** SPKI PEM (node:crypto createPublicKey format). */
  publicKeyPem: string;
}

