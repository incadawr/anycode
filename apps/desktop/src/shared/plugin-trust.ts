/**
 * §9.14 gate: the official channel is "configured" only when at least one
 * NON-test key is compiled in. A packaged build with only test keys reports
 * status "not configured" and the scheduler/install paths treat the channel
 * as disabled.
 */
export function isOfficialChannelConfigured(
  keys: readonly OfficialPluginKey[] = OFFICIAL_PLUGIN_KEYS,
): boolean {
  return keys.some((key) => isProductionKey(key));
}

/** True when the key is a production anchor (not a `test-*` fixture). */
export function isProductionKey(key: OfficialPluginKey): boolean {
  return !key.keyId.startsWith(OFFICIAL_PLUGIN_TEST_KEY_ID_PREFIX);
}

/** The official index (design §3): dedicated repo, raw URL, `index.json` + `index.json.sig`. */
export const OFFICIAL_PLUGIN_INDEX_URL =
  "https://raw.githubusercontent.com/incadawr/anycode-plugins/main/index.json";

/** The signature sidecar URL for an index URL (`<url>.sig`). */
export function officialIndexSigUrl(indexUrl: string): string {
  return `${indexUrl}.sig`;
}

