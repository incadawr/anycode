  await vi.waitFor(() => expect(scan).toHaveBeenCalled());
  await api.reconcile();
  const preview = await handlers.get(ACCOUNT_SOURCES_PREVIEW_CHANNEL)!(event, { key: { plugin: "company", source: "cluster" }, connectionId: "conn" }) as { ok: boolean; token: string };
  expect(preview.ok).toBe(true);
  const before = handlers.get(ACCOUNT_SOURCES_GET_CHANNEL)!(event);
