import { mkdtemp, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { afterEach, expect, it, vi } from "vitest";
import { accountSourceHash, accountSourceSchema } from "@anycode/core/plugins-admin";
import { cloneDefaults } from "../../settings/schema.js";
import { loadSettings, saveSettings } from "../../settings/files.js";
import { AccountBindingService } from "./binding.js";
let dir: string;
afterEach(async () => { if (dir) await rm(dir, { recursive: true, force: true }); });
it("requires a matching dedicated connection and a fresh single-use preview", async () => {
  dir = await mkdtemp(join(tmpdir(), "account-bind-"));
  const path = join(dir, "settings.json");
  const settings = cloneDefaults();
  settings.provider.connections = [{ id: "conn", providerId: "custom:corp" }];
  settings.provider.custom = [{ id: "custom:corp", name: "Company", baseUrl: "https://gateway.example.com/v1", kind: "openai-compatible", models: [], authOptional: true }];
  await saveSettings(path, settings);
  const descriptor = accountSourceSchema.parse({ id: "cluster", protocol: "anycode.account.v1", displayName: "Company", gateway: { name: "Company", baseUrl: "https://gateway.example.com/v1", kind: "openai-compatible" }, apiBaseUrl: "https://gateway.example.com/account/" });
  const candidate = { plugin: "company", descriptor, descriptorHash: accountSourceHash(descriptor) };
  const changed = vi.fn();
  let key: string | undefined;
  const service = new AccountBindingService({ settingsPath: path, candidates: async () => [candidate], getSecret: async () => key, fetchFor: () => async () => new Response(JSON.stringify({ schemaVersion: "anycode.account-catalog.v1", accountId: "employee", revision: "1", complete: true, models: [] })), changed });
  const preview = await service.preview({ plugin: "company", source: "cluster" }, "conn");
  expect(preview.ok).toBe(true);
  if (!preview.ok) return;
  expect(await service.bind(preview.token)).toBe(true);
  expect(await service.bind(preview.token)).toBe(false);
  expect((await loadSettings(path)).settings.plugins?.accountSources?.[0]?.accountId).toBe("employee");
  expect(changed).toHaveBeenCalledTimes(1);
  const next = await service.preview({ plugin: "company", source: "cluster" }, "conn");
  if (!next.ok) throw new Error("preview failed");
  key = "synthetic replacement";
  expect(await service.bind(next.token)).toBe(false);
});
